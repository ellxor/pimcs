from __future__ import annotations
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable, Optional

import numpy as np
import subprocess
import tempfile as tmp


from .dicke import Dicke, DickeState
from .qoperator import QOperator, QLeafExpr, destroy, jspin, commutator


@dataclass
class Config:
	system: Dicke                              # the physical system (Hamiltonian + Lindblad loss rates)
	initial_state: float                       # initial state: for now this is just the symmetry breaking angle
	expectation_operators: list[QExpr]         # list of operators for expectation values

	# integration parameters
	output_count: float = 0                    # time points to output expectation values (linearly spaced)
	output_total: float = 0                    # total time of simulation
	jump_tolerance: float = 1.0e-2             # tolerance to control expoential decay accuracy of loss channels
	hamiltonian_tolerance: float = 1.0e-10     # tolerance of vector norm of taylor series term
	number_of_trajectories: int = None         # total number of Monte Carlo simulations to average over
	number_of_cpus: int = None                 # total number of simulations to run in parallel

	# internal information related to wavefunction state
	displacement_optimisation: bool = False    # manually enabled by the user
	diagonal_state_optimisation: bool = False  # flatten 2D state to diagonal slice when Hamiltonian + initial state
											   # constrains to a single diagonal, e.g. Tavis-Cummings model
	spin_width: int = 0                        # maximum "width" of spin operators

	# generated by self
	function_table: list[Callable] = None
	hamiltonian_code: str = ""
	observables_code: str = ""
	output_file = None


def generate_hamiltonian_code(config: Config) -> str:
	code: str = ""

	for coeff, ops, funcs in config.system.hamiltonian.to_sum_of_products():
		spin_shift: int = 0
		photon_shift: int = 0

		weights: list[str] = []
		weights.append( f"({coeff.real} + {coeff.imag} * I)" )

		for op in reversed(ops):
			match op:
				case QOperator.Destroy:
					weights.append( f"sqrt(a + {photon_shift})" )
					photon_shift -= 1
				case QOperator.Create:
					weights.append( f"sqrt(a + 1 + {photon_shift})" )
					photon_shift += 1
				case QOperator.Jm:
					weights.append( f"sqrt((jmm + 1 + {spin_shift}) * (jpm - {spin_shift}))" )
					spin_shift -= 1
				case QOperator.Jp:
					weights.append( f"sqrt((jpm + 1 - {spin_shift}) * (jmm + {spin_shift}))" )
					spin_shift += 1
				case QOperator.Jz:
					weights.append( f"(m + {spin_shift})" )
				case QOperator.Alpha:
					weights.append( f"(src->alpha)" )
				case QOperator.AlphaConj:
					weights.append( f"conj(src->alpha)" )
				case _:
					raise AssertionError("unreachable code path reached!!!")

		for func in funcs:
			if config.function_table is None:
				config.function_table = []

			if func in config.function_table:
				index = config.function_table.index(func)

			else:
				index = len(config.function_table)
				config.function_table.append(func)

			weights.append( f"function_table[{index}][dst->time_slice]" )

		config.spin_width = max(config.spin_width, spin_shift)

		spin_shift: str = f"{spin_shift} * SPIN_SHIFT"
		photon_shift: str = f"{photon_shift} * PHOTON_SHIFT"
		factor: str = " * ".join(weights)

		# add bounds checking
		if not config.diagonal_state_optimisation:
			code += f"if ((a + {photon_shift}) >= 0 && (a + {photon_shift}) <= PHOTON_TRUNCATION) "

		code += f"dst->coeffs[index + {spin_shift} + {photon_shift}] += coeff * {factor}; "

	return code


# @todo: cleanup this function with the one above - significant overlap between the two
def generate_observables_code(config: Config) -> str:
	code: str = ""

	for expr_index, expr in enumerate(config.expectation_operators):
		for coeff, ops, funcs in expr.to_sum_of_products():
			spin_shift: int = 0
			photon_shift: int = 0

			if len(funcs) != 0:
				print("Error: functions are not handled in operator expectations")
				print(" > do this manually with the output of operator expectations")
				raise ValueError

			weights: list[str] = []
			weights.append( f"({coeff.real} + {coeff.imag} * I)" )

			for op in reversed(ops):
				match op:
					case QOperator.Destroy:
						weights.append( f"safe_sqrt(a + {photon_shift})" )
						photon_shift -= 1
					case QOperator.Create:
						weights.append( f"safe_sqrt(a + 1 + {photon_shift})" )
						photon_shift += 1
					case QOperator.Jm:
						weights.append( f"safe_sqrt((jmm + 1 + {spin_shift}) * (jpm - {spin_shift}))" )
						spin_shift -= 1
					case QOperator.Jp:
						weights.append( f"safe_sqrt((jpm + 1 - {spin_shift}) * (jmm + {spin_shift}))" )
						spin_shift += 1
					case QOperator.Jz:
						weights.append( f"(m + {spin_shift})" )
					case QOperator.Alpha:
						weights.append( f"(wave->alpha)" )
					case QOperator.AlphaConj:
						weights.append( f"conj(wave->alpha)" )
					case _:
						raise AssertionError("unreachable code path reached!!!")

			config.spin_width = max(config.spin_width, spin_shift)

			spin_shift: str = f"{spin_shift} * SPIN_SHIFT"
			photon_shift: str = f"{photon_shift} * PHOTON_SHIFT"
			factor: str = " * ".join(weights)

			# add bounds checking
			if not config.diagonal_state_optimisation:
				code += f"if ((a + {photon_shift}) >= 0 && (a + {photon_shift}) <= PHOTON_TRUNCATION) "

			# writing to: double complex expectation[THREAD_COUNT][OUTPUT_COUNT][OBSERVABLES_COUNT]
			code += f"expectation[thread_index][write_index][{expr_index}] += conj(wave->coeffs[index + {spin_shift} + {photon_shift}]) * wave->coeffs[index] * {factor}; "

	return code


def build_config(config: Config) -> list[str]:
	options: dict[str,str] = {
		"SB_ANGLE":                  config.initial_state.angle,
		"JUMP_TOLERANCE":            config.jump_tolerance,
		"HAMILTONIAN_TOLERANCE":     config.hamiltonian_tolerance,
		"TRAJECTORY_COUNT":          config.number_of_trajectories,
		"THREAD_COUNT":              config.number_of_cpus,
		"SPIN_WIDTH":                config.spin_width,
		"HAMILTONIAN_CODE":          config.hamiltonian_code,
		"OBSERVABLES_CODE":          config.observables_code,
		"OBSERVABLES_COUNT":         len(config.expectation_operators),

		"N":                         config.system.number_of_emitters,
		"PHOTON_TRUNCATION":         config.system.photon_truncation,
		"PHOTON_LOSS_RATE":          config.system.photon_loss_rate,
		"LOCAL_DEPHASING_RATE":      config.system.local_dephasing_rate,
		"LOCAL_EMISSION_RATE":       config.system.local_emission_rate,
		"LOCAL_PUMPING_RATE":        config.system.local_pumping_rate,
		"COLLECTIVE_DEPHASING_RATE": config.system.collective_dephasing_rate,
		"COLLECTIVE_EMISSION_RATE":  config.system.collective_emission_rate,
		"COLLECTIVE_PUMPING_RATE":   config.system.collective_pumping_rate,
		"CAVITY_ABSORPTION_RATE":    config.system.cavity_absorption_rate,
		"CAVITY_EMISSION_RATE":      config.system.cavity_emission_rate,

		"SIMULATION_TIME":           config.output_total,
		"OUTPUT_COUNT":              config.output_count,
		"OUTPUT_FILE":               f"\"{config.output_file.name}\"",
	}

	if config.displacement_optimisation:
		options["DISPLACEMENT"] = ""

	if config.diagonal_state_optimisation:
		options["DIAGONAL_STATE"] = ""

	if config.function_table is not None:
		times = np.linspace(0, config.output_total, config.output_count)
		table = [f(times) for f in config.function_table]

		code: str = f"double function_table[{len(config.function_table)}][{config.output_count}] = "
		code += "{"
		code += ",".join(["{" + ",".join([str(v) for v in vs]) + "}" for vs in table])
		code += "}"

		options["EMBED_FUNCTION_TABLES"] = code

	return [
		f"-D{option_name}={option_value}"
		for option_name, option_value in options.items()
	]


def mcsolve(
		system: Dicke,
		initial_state: DickeState,
		output_times: Iterable[float],
		expectation_operators: Iterable[QExpr],
		number_of_trajectories: int,
		number_of_cpus: int = None,
		enable_displacement: bool = False):

	if not isinstance(system, Dicke):
		print("Error: argument system is not a Dicke class.")
		print(" > use Dicke() to create one")
		raise ValueError

	if not isinstance(initial_state, DickeState):
		print("Error: argument initial_state is not a DickeState class.")
		print(" > use ground(), excited(), coherent_state(), or rotated_qubits(angle) to create one")
		raise ValueError

	if enable_displacement and (system.cavity_absorption_rate != 0 or system.cavity_emission_rate != 0):
		print("Error: cavity jump operators cannot currently be used with displacement transform")
		raise ValueError

	if number_of_cpus is None:
		print("Warning: CPU count not specified, defaulting to only a single core!")
		print(" > to remove this warning, explicitly pass number_of_cpus = 1 to mcsolve()")
		number_of_cpus = 1

	output_times = np.array(output_times, dtype = np.float64)
	output_delta = np.diff(output_times)

	if not np.allclose(output_delta, output_delta[0]):
		print("Error: output times must be linearly spaced for now")
		print(" > to request a change to this behaviour, open a GitHub issue")

	config = Config(
		system                    = system,
		initial_state             = initial_state,
		expectation_operators     = list(expectation_operators),
		number_of_trajectories    = number_of_trajectories,
		number_of_cpus            = number_of_cpus,
		output_total              = output_times[-1] - output_times[0],
		output_count              = len(output_times),
		displacement_optimisation = enable_displacement,
	)

	a = destroy()
	jz = jspin("z")
	excitation_operator = a.dag() * a + jz

	# check if hamiltonian commutes with excitation operator, and that initial state is an eigenstate of it
	if commutator(system.hamiltonian, excitation_operator) == 0 and config.initial_state.angle in (0, np.pi):
		if enable_displacement:
			print("Warning: this system and initial state can make use of a digonal state optimisation")
			print(" > this is faster than using the displacement method")

		else:
			config.diagonal_state_optimisation = True

			if config.system.photon_truncation > 0:
				print(f"Info: using diagonal state optimisation, photon truncation of {config.system.photon_truncation} ignored.")
				print(" > this mode can handle an unbounded photon Hilbert space")

				config.system.photon_truncation = 0

			# expectation operators are zero for operators that do not commute with excitation operator
			for i, op in enumerate(config.expectation_operators):
				if commutator(op, excitation_operator) != 0:
					config.expectation_operators[i] = QLeafExpr(0)

	if not config.output_total > 0:
		print("Error: output times is not monotonically increasing")

	if enable_displacement:
		config.system.hamiltonian = system.hamiltonian.displace()
		config.expectation_operators = [op.displace() for op in expectation_operators]

	config.output_file = tmp.NamedTemporaryFile()
	config.hamiltonian_code = generate_hamiltonian_code(config)
	config.observables_code = generate_observables_code(config)

	build_flags = build_config(config)
	c_flags = ["-O3", "-march=native", "-ffast-math", "-lm", "-g"] # @todo: allow the user to provide their own config
	target = Path(__file__).resolve().parent/"backend"/"main.c"

	with tmp.NamedTemporaryFile() as executable: # @hack: create a temporary file just to get an available file name,
		executable.close()                       #        then immediately delete it to then use that name
		subprocess.run(["cc", *build_flags, *c_flags, str(target), "-o", executable.name])
		subprocess.run([executable.name])

	data = np.loadtxt(config.output_file.name).T

	return [
		data[2*i] + (0 if op.is_hermitian() else 1j * data[2*i + 1]) # force Hermitian operators to have real expectation values
		for i, op in enumerate(config.expectation_operators)
	]
